local fakes = dofile("spec/support/fakes.lua")
local LidSensor = dofile("lid.lua")

describe("LidSensor.parse", function()
  it("maps the three ioreg outputs", function()
    assert.is_true(LidSensor.parse('    | |   "AppleClamshellState" = Yes\n'))
    assert.is_false(LidSensor.parse('    | |   "AppleClamshellState" = No\n'))
    assert.is_nil(LidSensor.parse('+-o Root  <class IORegistryEntry>\n'))
    assert.is_nil(LidSensor.parse(""))
  end)
end)

describe("LidSensor instance", function()
  local timer, screens, changes

  local function build(script, onReady)
    timer = fakes.timer()
    screens = fakes.screenWatcher()
    changes = {}
    local task = fakes.task(script)
    local lid = LidSensor.new({ screenWatcher = screens, task = task, timer = timer })
    lid:start(function(closed) changes[#changes + 1] = closed end, onReady)
    return lid, task
  end

  local NO = { 0, '"AppleClamshellState" = No' }
  local YES = { 0, '"AppleClamshellState" = Yes' }

  it("runs without a global hs", function()
    assert.is_nil(_G.hs)
  end)

  it("reads ioreg asynchronously on start", function()
    local lid, task = build({ NO })
    assert.is_nil(lid:closed())
    assert.are.equal("/usr/sbin/ioreg", task.created[1].path)
    assert.are.same({ "-r", "-k", "AppleClamshellState", "-d", "1" }, task.created[1].args)
    task.finish()
    assert.is_false(lid:closed())
    assert.are.same({}, changes)
    assert.are.equal(1, #screens.watchers)
    assert.is_true(screens.watchers[1].started)
  end)

  describe("onReady", function()
    local ready
    local function onReady(...) ready[#ready + 1] = table.pack(...) end

    before_each(function() ready = {} end)

    it("is called once with true when the first read says the lid is closed", function()
      local lid, task = build({ YES, NO }, onReady)
      assert.are.equal(0, #ready)
      task.finish()
      assert.are.equal(1, #ready)
      assert.is_true(ready[1][1])
      assert.is_true(lid:closed())
      assert.are.same({}, changes)
    end)

    it("is called with false when the lid is open", function()
      local _, task = build({ NO }, onReady)
      task.finish()
      assert.are.equal(1, #ready)
      assert.is_false(ready[1][1])
    end)

    it("is called with nil when there is no lid or ioreg fails", function()
      local _, task = build({ { 0, "no such key" } }, onReady)
      task.finish()
      assert.are.equal(1, #ready)
      assert.is_nil(ready[1][1])
      ready = {}
      _, task = build({ { 1, "", "boom" } }, onReady)
      task.finish()
      assert.are.equal(1, #ready)
      assert.is_nil(ready[1][1])
    end)

    it("is not called again for later changes", function()
      local _, task = build({ NO, YES }, onReady)
      task.finish()
      screens.fire()
      timer.advance(1.5)
      task.finish()
      assert.are.same({ true }, changes)
      assert.are.equal(1, #ready)
    end)

    it("is not called when the sensor is stopped before the read completes", function()
      local lid = build({ YES }, onReady)
      lid:stop()
      assert.are.equal(0, #ready)
    end)

    it("is optional", function()
      local lid, task = build({ YES })
      task.finish()
      assert.is_true(lid:closed())
    end)
  end)

  it("debounces screen changes into a single read and reports the change once", function()
    local lid, task = build({ NO, YES })
    task.finish()
    screens.fire()
    timer.advance(1.0)
    screens.fire()
    timer.advance(1.0)
    assert.are.equal(1, #task.created)
    timer.advance(0.5)
    assert.are.equal(2, #task.created)
    task.finish()
    assert.is_true(lid:closed())
    assert.are.same({ true }, changes)
  end)

  it("does not report when the lid state is unchanged", function()
    local _, task = build({ NO, NO })
    task.finish()
    screens.fire()
    timer.advance(1.5)
    task.finish()
    assert.are.same({}, changes)
  end)

  it("stays inactive and registers no watcher when there is no lid", function()
    local lid, task = build({ { 0, "no such key" } })
    task.finish()
    assert.is_nil(lid:closed())
    assert.are.equal(0, #screens.watchers)
  end)

  it("stays inactive when ioreg fails", function()
    local lid, task = build({ { 1, "", "boom" } })
    task.finish()
    assert.is_nil(lid:closed())
    assert.are.equal(0, #screens.watchers)
  end)

  it("keeps the last state when a later read fails", function()
    local lid, task = build({ NO, { 1, "" } })
    task.finish()
    screens.fire()
    timer.advance(1.5)
    task.finish()
    assert.is_false(lid:closed())
    assert.are.same({}, changes)
  end)

  it("stop cancels the watcher and pending debounce", function()
    local lid, task = build({ NO, YES })
    task.finish()
    screens.fire()
    lid:stop()
    timer.advance(5)
    assert.are.equal(1, #task.created)
    assert.is_true(screens.watchers[1].stopped)
    assert.are.same({}, changes)
  end)

  it("stop terminates the in-flight read and its callback has no side effects", function()
    local lid, task = build({ NO })
    lid:stop()
    assert.is_true(task.created[1].terminated)
    assert.is_nil(lid:closed())
    assert.are.same({}, changes)
    assert.are.equal(0, #screens.watchers)
  end)

  it("a stale terminated callback does not clobber a read started after restart", function()
    local lid, task = build({ NO, YES, YES })
    task.finish(1)
    screens.fire()
    timer.advance(1.5)
    lid:stop()
    assert.is_true(task.created[2].terminated)
    assert.are.same({}, changes)

    -- restart while the old read's terminated callback is delivered late
    local stale = task.created[2]
    lid:start(function(closed) changes[#changes + 1] = closed end)
    local fresh = task.created[3]
    stale.callback(15, "", "")
    assert.is_nil(fresh.terminated)
    assert.is_true(fresh.isRunning())
    task.finish(3)
    assert.are.equal(2, #screens.watchers)
    assert.is_true(screens.watchers[2].started)
    assert.is_true(lid:closed())
  end)

  it("stop after a stale callback still terminates the restarted read", function()
    local lid, task = build({ NO, NO })
    lid:stop()
    local stale = task.created[1]
    lid:start(function(closed) changes[#changes + 1] = closed end)
    stale.callback(15, "", "")
    lid:stop()
    assert.is_true(task.created[2].terminated)
  end)
end)
